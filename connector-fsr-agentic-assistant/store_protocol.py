"""The storage interface the connector's ops modules program against.

`SessionStore` is the one contract. `storage.Storage` (sqlite, one file on the
worker's disk) is its only implementation. A future backend is one new class
that satisfies this protocol, plus a line in `storage.default_storage`; no ops
module changes. The signatures below are generated from `Storage`, and a test
(tests/test_store_protocol.py) fails if they drift, so this file is never a
second list to keep by hand.

FortiSOAR-module-backed state (personas, skills, activity logs) is NOT behind
this interface: it lives on the platform and is reached through the platform
client, not through a local store.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol


